    /**
     * A guard over the source rather than over one behaviour: every operator the public
     * catalogue declares appears in the matrix, for every type that has one. Add an
     * operator to `FilterComparator` without a line here and this essay says so — which is
     * the only way a matrix stays a matrix.
     */
    public function testTheMatrixCoversEveryDeclaredOperator() :void
    {
        $declared = array_values( array_filter
        (
            FilterComparator::getAll() ,
            static fn( string $name ) => !str_starts_with( $name , '__' ) ,
            ARRAY_FILTER_USE_KEY
        ) ) ;

        $covered = [] ;
        foreach ( [ ...self::soundCombinations() , ...self::refusedCombinations() ] as $case )
        {
            $covered[ $case[ 1 ] ] = true ;
        }

        $missing = array_values( array_diff( $declared , array_keys( $covered ) ) ) ;

        // Not vacuous: an empty catalogue would satisfy the diff above without measuring anything.
        $this->assertGreaterThanOrEqual( 22 , count( $declared ) ) ;
        $this->assertSame( [] , $missing , 'every declared operator must appear in the matrix' ) ;
    }

    /**
     * The five comparator types are each measured against the whole catalogue — 22
     * operators apiece. `geo` is not one of them: it ignores `op` entirely and answers to
     * its own contract, below.
     */
    public function testEveryTypeIsMeasuredAgainstTheWholeCatalogue() :void
    {
        $perType = [] ;
        foreach ( [ ...self::soundCombinations() , ...self::refusedCombinations() ] as $name => $case )
        {
            $perType[ explode( ' ' , (string) $name )[ 0 ] ][] = $case[ 1 ] ;
        }

        $this->assertCount( 5 , $perType ) ;

        foreach ( $perType as $type => $ops )
        {
            $this->assertCount( 22 , array_unique( $ops ) , "the $type type is not fully measured" ) ;
        }
    }

    // ---------------------------------------------------------------- the two contracts that are not operators

    /**
     * No `op` at all is an equality — that is the documented default, and the one case
     * where falling back to `==` is what the caller meant.
     */
    public function testAnAbsentOperatorIsAnEquality() :void
    {
        $this->assertSame( 'doc.name == @v0' , $this->compile( 'name' , null , 'AC' ) ) ;
    }

    /**
     * The geo filter answers to `min` / `max` rather than to `op`, and emits nothing at all
     * without a radius — documented, and the one legitimately empty cell of the matrix.
     */
    public function testTheGeoFilterAnswersToItsOwnContract() :void
    {
        $point = [ 'latitude' => 48.85 , 'longitude' => 2.35 ] ;

        $this->assertSame
        (
            'DISTANCE(doc.geo.latitude,doc.geo.longitude,@v0,@v1) <= @v2' ,
            $this->compile( 'geo' , 'distance' , $point , [ 'max' => 5000 ] )
        ) ;

        // No radius, no clause — a filter that cannot be honoured is not silently widened.
        $this->assertSame( '' , $this->compile( 'geo' , 'distance' , $point ) ) ;
    }

