    /**
     * Compiles one filter and renumbers its bind tokens, which carry a random suffix.
     */
    private function compile( string $field , ?string $op , mixed $value , array $extra = [] ) :string
    {
        $init = [ 'key' => $field , ...$extra ] ;

        if ( $op !== null )
        {
            $init[ 'op' ] = $op ;
        }

        if ( $op === 'between' )
        {
            $init[ 'min' ] = 1 ;
            $init[ 'max' ] = 9 ;
        }
        else
        {
            $init[ 'val' ] = $value ;
        }

        $binds = [] ;
        $index = 0 ;

        return (string) preg_replace_callback
        (
            '/@query_\\d+_\\d+/' ,
            static function () use ( &$index ) { return '@v' . $index++ ; } ,
            (string) $this->model->prepareFilter( $init , $binds )
        ) ;
    }
