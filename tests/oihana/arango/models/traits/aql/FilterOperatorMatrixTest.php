/**
 * The AQL every `op` compiles to, for every filter type, pinned character for character.
 *
 * The essays around this one check **fragments** — that the field appears, that an `==`
 * appears somewhere. That is not enough to catch the failure this file exists for: when an
 * operator silently degrades to an equality, an assertion looking for `==` turns **green**.
 * Only the whole expression, compared as a whole, says what the query really means.
 *
 * The matrix is generated by driving a real `Documents` model, so it reads what a caller
 * would get, not what a double was told to answer. Bind tokens carry a random suffix, so
 * they are renumbered in order of appearance (`@v0`, `@v1`, …) before comparison.
 *
 * @package tests\oihana\arango\models\traits\aql
 * @author  Marc Alcaraz
 */
class FilterOperatorMatrixTest extends TestCase
{
    private Documents $model ;

    protected function setUp() :void
    {
        $container = new Container() ;
        $container->set( LoggerInterface::class , new NullLogger() ) ;

        $this->model = new Documents( $container ,
        [
            AQL::COLLECTION => 'items' ,
            AQL::LAZY       => false   ,
            AQL::FILTERS    =>
            [
                'name'    => FilterType::STRING ,
                'age'     => FilterType::NUMBER ,
                'active'  => FilterType::BOOL   ,
                'created' => FilterType::DATE   ,
                'tags'    => FilterType::ARRAY  ,
                'geo'     => FilterType::GEO    ,
            ] ,
        ]) ;
    }

    // ---------------------------------------------------------------- the matrix

    /**
     * Every combination that compiles to what its operator means.
     */
    #[DataProvider( 'soundCombinations' )]
    public function testTheOperatorCompilesToWhatItMeans( string $field , string $op , mixed $value , string $expected ) :void
    {
        $this->assertSame( $expected , $this->compile( $field , $op , $value ) ) ;
    }

    /**
     * The other half of the matrix: an operator this filter type cannot honour is refused,
     * naming what was refused.
     *
     * ⚠ Until 1.6.0 every one of these compiled to an equality. `distance` on a non-geo
     * field, and every function form outside `string` — `contains`, `sw`, `ew`, `regex`
     * and their negations — plus `between` on `bool` and `array`.
     * `{"key":"price","op":"sw","val":12}` asked for prices *starting with* 12 and answered
     * prices *equal to* 12: a handful of plausible rows, in `200`, answering a question
     * nobody asked. An empty page gets noticed; a wrong page does not.
     */
    #[DataProvider( 'refusedCombinations' )]
    public function testAnOperatorTheTypeCannotHonourIsRefused( string $field , string $op , mixed $value ) :void
    {
        try
        {
            $this->compile( $field , $op , $value ) ;
            $this->fail( sprintf( 'the "%s" operator must be refused on "%s"' , $op , $field ) ) ;
        }
        catch ( RequestValidationException $exception )
        {
            $this->assertSame( HttpStatusCode::BAD_REQUEST , $exception->getCode() ) ;
            $this->assertStringContainsString( sprintf( '"%s"' , $op ) , $exception->getMessage() ) ;
        }
    }

