    {
        $this->expectException( RequestValidationException::class ) ;
        $this->expectExceptionMessage( 'Unsupported filter operator "zzz"' ) ;

        $binds = [] ;
        $this->model->prepareFilter( [ 'key' => 'tags' , 'quant' => 'any' , 'op' => 'zzz' , 'val' => 'AC' ] , $binds ) ;
    }

